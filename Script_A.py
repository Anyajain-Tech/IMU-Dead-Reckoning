# Aggregate correlation per trip (should be strongly positive if calibration worked)
def fwd_lat_corr(g):
    v = g["veh_Velocity"].values / 3.6
    t_ = g["t_rel_phone"].values
    a_fwd = np.gradient(v, t_)
    a_lat = np.radians(g["veh_YawRate"].values) * v
    move = g["zupt_label"].values == 0
    if move.sum() < 10:
        return pd.Series({"corr_fwd": np.nan, "corr_lat": np.nan})
    return pd.Series({
        "corr_fwd": np.corrcoef(g["acc_x_veh"].values[move], a_fwd[move])[0, 1],
        "corr_lat": np.corrcoef(g["acc_y_veh"].values[move], a_lat[move])[0, 1],
    })

corr_table = final_df.groupby("trip_id").apply(fwd_lat_corr, include_groups=False).sort_values("corr_fwd")
print("CHECK 10c: per-trip correlation between phone-calibrated and ground-truth accel (closer to 1 = better)")
print(corr_table.to_string())
print(f"\nMean corr_fwd: {corr_table['corr_fwd'].mean():.3f}   Mean corr_lat: {corr_table['corr_lat'].mean():.3f}")